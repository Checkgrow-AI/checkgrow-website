# ---- triggers -----------------------------------------------------------------
def cond(ctype, arg0, arg1, **extra):
    p = [tpl("arg0", arg0), tpl("arg1", arg1)]
    p += [boolean(k, v) for k, v in extra.items()]
    return {"type": ctype, "parameter": p}


def trigger(name, ttype, filters=(), custom_event=None, **extra):
    tid = str(next(ids))
    t = {**base, "triggerId": tid, "name": name, "type": ttype, "notes": NOTE}
    if custom_event:
        t["customEventFilter"] = [cond("EQUALS", "{{_event}}", custom_event)]
    if filters:
        t["filter"] = list(filters)
    t.update(extra)
    triggers.append(t)
    return tid


