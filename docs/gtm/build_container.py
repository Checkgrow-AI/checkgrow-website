# ---- variables ----------------------------------------------------------------
def var(name, vtype, params, notes="", fid=F_VARS):
    variables.append(
        {
            **base,
            "variableId": str(next(ids)),
            "name": name,
            "type": vtype,
            "notes": notes or NOTE,
            "parameter": params,
            "parentFolderId": fid,
            "formatValue": {},
        }
    )
    return "{{" + name + "}}"


def const(name, value, notes=""):
    return var(name, "c", [tpl("value", value)], notes)


def dlv(key):
    return var(
        f"DLV - {key}",
        "v",
        [boolean("setDefaultValue", False), tpl("name", key), {"type": "INTEGER", "key": "dataLayerVersion", "value": "2"}],
    )


def cookie(name, notes):
    return var(f"Cookie - {name}", "k", [boolean("decodeCookie", True), tpl("name", name)], notes)


