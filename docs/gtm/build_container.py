def meta(name, standard_event, fire, once="ONCE_PER_EVENT", event_id=True):
    params = [
        boolean("disablePushState", True),  # page changes are sent explicitly by the History tag
        tpl("pixelId", V_META),
        tpl("standardEventName", standard_event),
        boolean("disableAutoConfig", False),
        boolean("enhancedEcommerce", False),
        boolean("dpoLDU", False),
        tpl("eventName", "standard"),
        boolean("objectPropertiesFromVariable", False),
        boolean("consent", True),
        boolean("advancedMatching", False),
    ]
    if event_id:
        params.append(tpl("eventId", V_EVENT_ID))
        params.append({"type": "LIST", "key": "objectPropertyList", "list": [
            {"type": "MAP", "map": [tpl("name", "content_name"), tpl("value", "Book a demo")]},
            {"type": "MAP", "map": [tpl("name", "lead_source"), tpl("value", V_SRC)]},
            {"type": "MAP", "map": [tpl("name", "lead_campaign"), tpl("value", V_CMP)]},
        ]})
    tag(name, META_TYPE, params, fire, F_META, once, consent=["ad_storage"])


