def ga4_event(name, event, fire, params):
    tag(name, "gaawe", [
        boolean("sendEcommerceData", False),
        tpl("eventName", event),
        tpl("measurementIdOverride", V_GA4),
        table("eventSettingsTable", params),
    ], fire, F_GA4)


