def ads_conversion(name, label, fire, paused=False, notes=""):
    tag(name, "awct", [
        boolean("enableNewCustomerReporting", False),
        boolean("enableConversionLinker", True),
        tpl("orderId", V_EVENT_ID),
        boolean("enableProductReporting", False),
        # no conversionValue: the value set on the conversion action in Google Ads applies
        boolean("enableShippingData", False),
        tpl("conversionId", V_ADS_ID),
        tpl("currencyCode", "EUR"),
        tpl("conversionLabel", label),
        boolean("rdp", False),
    ], fire, F_ADS, paused=paused, notes=notes)


ads_conversion("Google Ads - Conversion - Demo lead", V_ADS_LEAD, [T_LEAD])
ads_conversion("Google Ads - Conversion - Demo booked", V_ADS_BOOKED, [T_BOOKED])

