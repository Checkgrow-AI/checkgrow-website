def tpl(key, value):
    return {"type": "TEMPLATE", "key": key, "value": str(value)}


def boolean(key, value):
    return {"type": "BOOLEAN", "key": key, "value": "true" if value else "false"}


def table(key, rows, k="parameter", v="parameterValue"):
    return {
        "type": "LIST",
        "key": key,
        "list": [{"type": "MAP", "map": [tpl(k, a), tpl(v, b)]} for a, b in rows],
    }


def folder(name):
    fid = str(next(ids))
    folders.append({**base, "folderId": fid, "name": name})
    return fid


