#!/usr/bin/env node
/* Imports the nine animated Sales mockups from the "Checkgrow Material"
   design canvas (page "Animated mockups · use-case pages") into the site.

   Usage: node scripts/import-sales-mockups.mjs <folder with the .dc.html files>

   Each mockup is static markup plus CSS keyframes. The script keeps the
   markup inside <x-dc> (minus <helmet>), prefixes every class and keyframe
   name with the mockup's key so the nine can share a page, points
   /_blob/<id> images at public/sales/mockups/<id>.(webp|svg), and writes
   src/components/sales/salesMockups.generated.ts. Images are optimised
   separately into public/sales/mockups. */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SOURCE = process.argv[2];
if (!SOURCE) {
  console.error("Usage: node scripts/import-sales-mockups.mjs <folder>");
  process.exit(1);
}

const MOCKUPS = [
  ["lists-1", "Anim-Lists-1-ICP-To-Ranked-List"],
  ["lists-2", "Anim-Lists-2-Right-Person-First"],
  ["lists-3", "Anim-Lists-3-Lists-Route-Themselves"],
  ["outreach-1", "Anim-Outreach-1-Warm-Up-Before-Pitch"],
  ["outreach-2", "Anim-Outreach-2-Approve-In-Minutes"],
  ["outreach-3", "Anim-Outreach-3-Replies-Read-And-Sorted"],
  ["brain-1", "Anim-Brain-1-Feedback-Writes-Next-Message"],
  ["brain-2", "Anim-Brain-2-Learns-From-Every-Signal"],
  ["brain-3", "Anim-Brain-3-More-Replies-Every-Week"],
];

const ASSETS = "public/sales/mockups";
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const out = MOCKUPS.map(([key, file]) => {
  const src = readFileSync(join(SOURCE, `${file}.dc.html`), "utf8");
  const helmet = src.match(/<helmet>([\s\S]*?)<\/helmet>/)?.[1] ?? "";
  let css = [...helmet.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");
  let html = src.match(/<\/helmet>([\s\S]*?)<\/x-dc>/)?.[1] ?? "";
  if (!html.trim()) throw new Error(`${file}: no markup`);

  const prefix = `sm-${key}-`;
  css = css.replace(/body\{margin:0\}/g, "");

  const keyframes = [...css.matchAll(/@keyframes\s+([A-Za-z_][\w-]*)/g)].map((m) => m[1]);
  const classes = new Set(
    [...html.matchAll(/class="([^"]*)"/g)].flatMap((m) => m[1].split(/\s+/).filter(Boolean)),
  );

  // keyframe names: their declaration and every animation reference
  for (const name of new Set(keyframes)) {
    const word = new RegExp(`(?<![\\w-])${escapeRe(name)}(?![\\w-])`, "g");
    css = css.replace(new RegExp(`@keyframes\\s+${escapeRe(name)}(?![\\w-])`, "g"), `@keyframes ${prefix}${name}`);
    css = css.replace(/(animation(?:-name)?\s*:)([^;}]*)/g, (all, prop, value) =>
      prop + value.replace(word, `${prefix}${name}`),
    );
  }
  // class selectors
  for (const name of classes) {
    css = css.replace(new RegExp(`\\.${escapeRe(name)}(?![\\w-])`, "g"), `.${prefix}${name}`);
  }
  html = html.replace(/class="([^"]*)"/g, (_, list) =>
    `class="${list.split(/\s+/).filter(Boolean).map((c) => prefix + c).join(" ")}"`,
  );

  // images
  html = html.replace(/\/_blob\/([0-9a-f]{32})/g, (all, id) => {
    for (const ext of ["webp", "svg"]) {
      if (existsSync(join(ASSETS, `${id}.${ext}`))) return `/sales/mockups/${id}.${ext}`;
    }
    throw new Error(`${file}: missing asset ${id}`);
  });
  // the site serves Geist itself
  html = html.replaceAll("font-family: 'Geist', system-ui, sans-serif", "font-family: var(--font-geist-sans), system-ui, sans-serif");

  // the storyboard loop: the longest infinite animation (shimmers and floats are shorter)
  const loop = Math.max(...[...css.matchAll(/animation\s*:[^;}]*?(\d+(?:\.\d+)?)s[^;}]*infinite/g)].map((m) => Number(m[1])));
  return { key, css: css.trim(), html: html.trim().replace(/\n+/g, "\n"), loop };
});

const body = `/* Generated by scripts/import-sales-mockups.mjs from the "Checkgrow
   Material" design canvas. Do not edit by hand; re-run the script. */

export type SalesMockupKey = ${out.map((m) => JSON.stringify(m.key)).join(" | ")};

export const salesMockups: Record<SalesMockupKey, { css: string; html: string; loop: number }> = {
${out.map((m) => `  ${JSON.stringify(m.key)}: { loop: ${m.loop}, css: ${JSON.stringify(m.css)}, html: ${JSON.stringify(m.html)} },`).join("\n")}
};
`;
writeFileSync("src/components/sales/salesMockups.generated.ts", body);
console.log(out.map((m) => `${m.key}: ${m.loop}s, ${m.css.length} css, ${m.html.length} html`).join("\n"));
