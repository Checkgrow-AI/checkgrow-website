/* Extract the visible text of the generated product mockups into
   src/i18n/mockupTexts.generated.ts (with the screens each text appears
   on, as context for translators).

     node scripts/i18n/mockups.mjs           write the file
     node scripts/i18n/mockups.mjs --check   exit 1 if it is out of date

   Run it after regenerating src/lib/featureScreens.ts or
   src/components/sales/salesMockups.generated.ts, then translate the new
   texts in src/i18n/dictionaries/<lang>/mockups.ts. */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import ts from "typescript";

/* src/i18n/mockups.ts is loaded through the TypeScript compiler, not
   Node's own type stripping, so this runs on any Node version (the Easy
   Panel Docker build runs it through pnpm build) */
function loadMockupsModule() {
  const file = new URL("../../src/i18n/mockups.ts", import.meta.url);
  const code = ts.transpileModule(readFileSync(file, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const mod = { exports: {} };
  new Function("exports", "module", code)(mod.exports, mod);
  return mod.exports;
}
const { mockupTexts } = loadMockupsModule();

const ROOT = resolve(dirname(new URL(import.meta.url).pathname), "../..");
const OUT = join(ROOT, "src/i18n/mockupTexts.generated.ts");

export function collect() {
  const fs = readFileSync(join(ROOT, "src/lib/featureScreens.ts"), "utf8");
  const sm = readFileSync(join(ROOT, "src/components/sales/salesMockups.generated.ts"), "utf8");
  const screens = [
    ...[...fs.matchAll(/^\s*"([\w-]+)": "((?:[^"\\]|\\.)*)",?$/gm)].map((m) => ["features", m[1], JSON.parse(`"${m[2]}"`)]),
    ...[...sm.matchAll(/"([\w-]+)": \{ loop: [\d.]+, css: "(?:[^"\\]|\\.)*", html: "((?:[^"\\]|\\.)*)"/g)].map((m) => ["sales", m[1], JSON.parse(`"${m[2]}"`)]),
  ];
  const where = new Map();
  for (const [group, key, html] of screens) for (const t of mockupTexts(html)) {
    if (!where.has(t)) where.set(t, new Set());
    where.get(t).add(`${group}:${key}`);
  }
  return { screens: screens.length, where };
}

function render({ where }) {
  const entries = [...where.entries()].sort((a, b) => a[0].localeCompare(b[0], "en"));
  return `/* Generated by scripts/i18n/mockups.mjs from the product mockups. Do not
   edit by hand; re-run the script after regenerating a mockup.
   Each text maps to the screens it appears on (context for translators). */
export const mockupTexts: Readonly<Record<string, readonly string[]>> = {
${entries.map(([t, s]) => `  ${JSON.stringify(t)}: ${JSON.stringify([...s].sort())},`).join("\n")}
};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const data = collect();
  const next = render(data);
  if (process.argv.includes("--check")) {
    const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (cur !== next) {
      console.error("src/i18n/mockupTexts.generated.ts is out of date: run node scripts/i18n/mockups.mjs");
      process.exit(1);
    }
    console.log("mockup texts up to date.");
  } else {
    writeFileSync(OUT, next);
    console.log(`${data.where.size} texts from ${data.screens} mockups -> src/i18n/mockupTexts.generated.ts`);
  }
}
